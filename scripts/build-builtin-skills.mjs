#!/usr/bin/env node
// Builds the shipped skill catalog (pkg/rancher-desktop/agent/builtinSkills/builtin-skills.json)
// from the skill folders next to it. Each <slug>/ folder holds a SKILL.md and any extra files.
// Run: node scripts/build-builtin-skills.mjs   — then run the builtinSkills catalog test.
//
// The folders are the source you edit; the JSON is what the app bundle carries
// (same as builtin-agents.json) and what seedBuiltinSkills writes into the DB.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogDir = path.join(root, 'pkg/rancher-desktop/agent/builtinSkills');
const outFile = path.join(catalogDir, 'builtin-skills.json');
const SKIP = new Set(['.DS_Store', '.git', 'node_modules']);

function readTree(dir, prefix = '') {
  const files = {};
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (SKIP.has(entry.name)) continue;
    const abs = path.join(dir, entry.name);
    const rel = prefix ? `${ prefix }/${ entry.name }` : entry.name;
    if (entry.isDirectory()) Object.assign(files, readTree(abs, rel));
    else if (entry.isFile()) {
      const buffer = fs.readFileSync(abs);
      files[rel] = buffer.includes(0) ? { encoding: 'base64', content: buffer.toString('base64') } : buffer.toString('utf8');
    }
  }
  return files;
}

const previous = fs.existsSync(outFile) ? JSON.parse(fs.readFileSync(outFile, 'utf8')) : {};
const skills = fs.readdirSync(catalogDir, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && !entry.name.startsWith('.') && !entry.name.startsWith('__') && fs.existsSync(path.join(catalogDir, entry.name, 'SKILL.md')))
  .map(entry => entry.name)
  .sort()
  .map(slug => ({ slug, files: readTree(path.join(catalogDir, slug)) }));

const catalog = {
  $comment: 'Built-in skills shipped with Sulla Desktop. GENERATED by scripts/build-builtin-skills.mjs from the <slug>/ folders in this directory: edit the folder, then rerun the script. Seeded into skill_definitions at boot by seedBuiltinSkills.ts (insert if missing; refresh only rows untouched since the last seed). "retired" lists slugs the bundle no longer ships: the seeder disables its own untouched copy once and never deletes it.',
  skills,
  retired: Array.isArray(previous.retired) ? previous.retired : [],
};
fs.writeFileSync(outFile, `${ JSON.stringify(catalog, null, 2) }\n`);
console.log(`Wrote ${ skills.length } built-in skill(s) to ${ path.relative(root, outFile) }`);
