'use strict';

const childProcess = require('child_process');
const fs = require('fs');
const path = require('path');

const SOURCE_SHA = '43ac3ede766509792c81d91e2ffd2c4c555b6ab9';
const SERVER_DIR = path.join(__dirname, 'server');
const INSTALLER = path.join(SERVER_DIR, 'install.sh');
const ELEVATED_ARG = '--_sulla-server-elevated';

// These affect installer choices but contain no generated service credentials
// or hidden prompt answers. sudo receives variable names only, never values.
const CONFIG_ENV = [
  'INSTALL_K3S_VERSION',
  'K3S_URL',
  'KUBECONFIG',
  'SULLA_ADMIN_EMAIL',
  'SULLA_ADMIN_NAME',
  'SULLA_BIND_ADDRESS',
  'SULLA_DATA_DIR',
  'SULLA_DIR',
  'SULLA_HOSTNAME',
  'SULLA_INGRESS_MODE',
  'SULLA_KUBECONFIG',
  'SULLA_KUBECONTEXT',
  'SULLA_KUBERNETES_MODE',
  'SULLA_ORGANIZATION',
  'SULLA_PORT',
  'SULLA_PROJECTS_IMAGE',
  'SULLA_PUBLIC_URL',
  'SULLA_RUNTIME',
  'SULLA_STORAGE_CLASS',
  'SULLA_STORAGE_SIZE',
  'SULLA_TLS_CERT',
  'SULLA_TLS_KEY',
  'SULLA_TLS_SECRET',
  'SULLA_VAULT_IMAGE',
];

const REQUIRED_FILES = [
  'install.sh',
  'install-server.sh',
  'join-node.sh',
  'deploy-sulla.sh',
  'compose.yaml',
  'k8s/kustomization.yaml',
  'k8s/namespace.yaml',
  'k8s/storage.yaml',
  'k8s/postgres.yaml',
  'k8s/sulla-vault.yaml',
  'k8s/sulla-projects.yaml',
];

class ServerUserError extends Error {}

function printServerHelp(command) {
  console.log(`${ command } server — install Sulla Server on Linux

Usage:
  ${ command } server             Run the interactive server installer
  ${ command } server --dry-run   Verify the bundled kit and show the pinned release
  ${ command } server --help      Show this help

The installer asks whether to use Docker Compose or Kubernetes, then creates
the first owner through hidden terminal prompts. It needs root access and will
ask through sudo when necessary. Passwords, join tokens, and generated service
credentials are never passed on the command line.

New installations use Sulla source ${ SOURCE_SHA } and the matching published
server image. Existing /opt/sulla/server configuration remains authoritative
when the installer is rerun.`);
}

function assertLinux() {
  if (process.platform !== 'linux') {
    throw new ServerUserError('Sulla Server installation is supported on Linux. Run this command on the Linux server you want to install.');
  }
}

function assertBundle() {
  for (const relative of REQUIRED_FILES) {
    const file = path.join(SERVER_DIR, relative);

    if (!fs.statSync(file, { throwIfNoEntry: false })?.isFile()) {
      throw new Error(`The npm package is incomplete: missing server/${ relative }`);
    }
  }
}

function installerEnvironment() {
  const env = {};
  const safeBase = ['HOME', 'LANG', 'LC_ALL', 'LC_CTYPE', 'LOGNAME', 'NO_COLOR', 'PATH', 'SHELL', 'TERM', 'USER'];

  for (const name of [...safeBase, ...CONFIG_ENV]) {
    if (process.env[name] !== undefined) {
      env[name] = process.env[name];
    }
  }

  // Package releases deliberately launch a known source/image pair. Secrets
  // are generated by the installer or requested with terminal echo disabled.
  env.SULLA_SOURCE_SHA = SOURCE_SHA;
  env.SULLA_BUNDLE_DIR = SERVER_DIR;
  env.SULLA_BUNDLE_SOURCE_SHA = SOURCE_SHA;

  return env;
}

function run(command, args, options = {}) {
  const result = childProcess.spawnSync(command, args, { stdio: 'inherit', ...options });

  if (result.error) {
    if (command === 'sudo' && result.error.code === 'ENOENT') {
      throw new ServerUserError('Root access is required. Install sudo, or run this command from a root shell.');
    }
    throw result.error;
  }
  if (result.signal) {
    process.kill(process.pid, result.signal);

    return;
  }
  if (result.status !== 0) {
    process.exitCode = result.status || 1;
  }
}

function runServer(argv, command = 'npx sulla-desktop') {
  let elevated = false;
  let dryRun = false;

  for (const arg of argv) {
    if (arg === '--help' || arg === '-h') {
      printServerHelp(command);

      return;
    }
    if (arg === '--dry-run') {
      dryRun = true;
    } else if (arg === ELEVATED_ARG) {
      elevated = true;
    } else {
      throw new ServerUserError(`Unknown server option: ${ arg }\nRun "${ command } server --help" to see the options.`);
    }
  }

  assertLinux();
  assertBundle();

  if (dryRun) {
    console.log(`Sulla Server package is ready.\nSource:  ${ SOURCE_SHA }\nKit:     ${ SERVER_DIR }\nInstall: ${ process.env.SULLA_DIR || '/opt/sulla/server' }\nWould:   ${ typeof process.geteuid === 'function' && process.geteuid() === 0 ? 'run installer as root' : 'request root access with sudo, then run installer' }`);

    return;
  }

  if (typeof process.geteuid !== 'function') {
    throw new ServerUserError('Cannot determine Linux user privileges. Run this command from a standard Node.js installation.');
  }

  if (process.geteuid() !== 0) {
    if (elevated) {
      throw new ServerUserError('sudo did not grant root access.');
    }
    if (!process.env.KUBECONFIG && process.env.HOME) {
      const defaultKubeconfig = path.join(process.env.HOME, '.kube', 'config');

      if (fs.statSync(defaultKubeconfig, { throwIfNoEntry: false })?.isFile()) {
        // Preserve only the path. The installer snapshots the selected context
        // after elevation; this launcher never reads kubeconfig contents.
        process.env.KUBECONFIG = defaultKubeconfig;
      }
    }
    const preserve = CONFIG_ENV.filter(name => process.env[name] !== undefined).join(',');
    const args = [];

    if (preserve) {
      args.push(`--preserve-env=${ preserve }`);
    }
    args.push('--', process.execPath, path.join(__dirname, 'bin.js'), 'server', ELEVATED_ARG);
    run('sudo', args);

    return;
  }

  run('bash', [INSTALLER], { env: installerEnvironment() });
}

module.exports = { SOURCE_SHA, ServerUserError, printServerHelp, runServer };
