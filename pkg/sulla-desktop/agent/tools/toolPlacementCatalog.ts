// Builds resources/tool-placements.json, which Cloud and Mobile read. Only the
// generator (scripts/gen-tool-placements.mjs) and tests import this module.

import { createHash } from 'node:crypto';

import policy from './tool-placement-policy.json';
import { resolveToolPlacement, toolId, type PlacementManifest, type ToolPlacementMetadata } from './toolPlacement';

export interface ToolPlacementEntry extends ToolPlacementMetadata {
  category: string;
  name:     string;
}

export interface ToolPlacementCatalog {
  version:     number;
  /** SHA-256 of the JSON-encoded `tools` object, so readers can tell two catalogs apart. */
  contentHash: string;
  description: string;
  /** Keyed by `category/name`, sorted by code point. */
  tools:       Record<string, ToolPlacementEntry>;
}

const byCodePoint = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

export function buildToolPlacementCatalog(manifests: readonly PlacementManifest[]): ToolPlacementCatalog {
  const entries = new Map<string, ToolPlacementEntry>();
  for (const manifest of manifests) {
    const id = toolId(manifest.category, manifest.name);
    if (entries.has(id)) throw new Error(`Duplicate tool id ${ id }`);
    entries.set(id, { category: manifest.category, name: manifest.name, ...resolveToolPlacement(manifest) });
  }
  const tools = Object.fromEntries([...entries.keys()].sort(byCodePoint).map(id => [id, entries.get(id)!]));

  return {
    version:     policy.version,
    contentHash: `sha256:${ createHash('sha256').update(JSON.stringify(tools)).digest('hex') }`,
    description: 'placements lists the hosts eligible to run a tool; a host offers a tool only if it is eligible and also implements it. Generated by scripts/gen-tool-placements.mjs; do not edit.',
    tools,
  };
}

export function renderToolPlacementCatalog(manifests: readonly PlacementManifest[]): string {
  return `${ JSON.stringify(buildToolPlacementCatalog(manifests), null, 2) }\n`;
}
